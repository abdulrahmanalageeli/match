export function getSocialVotePrompts(activityId: SocialVoteActivityId, round: number) {
  const bank = activityId === "green-red-depends" ? greenRedDependsPrompts : unwrittenRulesPrompts;
  const offset = ((Math.max(1, Math.floor(round)) - 1) * 10) % bank.length;
  return [...bank.slice(offset), ...bank.slice(0, offset)];
}

export function summarizeSocialVotes(votes: readonly (string | null)[], choices: readonly string[]) {
  return choices.map(choice => ({ choice, count: votes.filter(vote => vote === choice).length }));
}
