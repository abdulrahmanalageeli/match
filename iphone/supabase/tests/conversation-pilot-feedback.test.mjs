import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { seedCommunicationMember, signCommunicationAgreement } from './communication-fixture.mjs';
import { createDatabase, addUser, asMember, asService } from './harness.mjs';
import { dimensions } from '../../src/compatibility/model.ts';
import traits from '../../src/compatibility/personality-catalog.json' with {type:'json'};

test('conversation pilot preserves private responses, freezes assignment and counts reciprocal outcomes', async () => {
  const db = await createDatabase();
  try {
    const rpc = async (sql, params = []) => (await db.query('select ' + sql + ' value', params)).rows[0].value;
    const call = (user, sql, params) => asMember(db, user.id, user.sessionId, () => rpc(sql, params));
    const service = (sql, params) => asService(db, () => rpc(sql, params));
    const add = async gender => {
      const id = randomUUID(), user = { id, sessionId: randomUUID(), email: id + '@example.test' };
      await addUser(db, user);
      await seedCommunicationMember(db, user, gender);
      await db.query("update marriage.members set manual_access_until=now()+interval '1 day' where id=$1", [id]);
      return user;
    };
    const a = await add('woman'), b = await add('man'), outsider = await add('man');
    const practical = Object.fromEntries(dimensions.flatMap(q => [[q.id, 'A'], [q.partnerId, 'A']]));
    const personality = {...Object.fromEntries(traits.map(q => [q.id, 'C'])), partner_social_energy:'C'};
    for (const user of [a, b]) {
      await db.query("insert into marriage.member_assessment(member_id,version) values($1,'marriage-v4') on conflict(member_id) do update set version=excluded.version", [user.id]);
      await db.query('insert into marriage.member_answers select $1,key,value from jsonb_each_text($2)', [user.id, practical]);
      await db.query('insert into marriage.personality_answers select $1,key,value from jsonb_each_text($2)', [user.id, personality]);
    }
    await call(a, 'public.marriage_discover()');
    const request = await call(a, 'public.marriage_request($1)', [b.id]);
    const enroll = 'public.marriage_enroll_conversation_pilot($1,$2)';
    const notices = user => call(user, 'public.marriage_conversation_pilot_notices()');
    const reply = (user, action = 'read', answer = null) =>
      call(user, 'public.marriage_conversation_pilot_response($1,$2,$3)', [request, action, answer]);
    await assert.rejects(call(a, enroll, [request, 'candidate']), /permission denied/);
    assert.equal(await service(enroll, [request, 'candidate']), true);
    assert.equal(await service(enroll, [request, 'baseline']), false);
    await db.query("update marriage.personality_answers set option_code='E' where member_id=$1 and question_code='partner_social_energy'", [a.id]);
    const { rows: [{ fit }] } = await db.query('select fit from marriage.pair_fit($1,$2)', [a.id,b.id]);
    assert.ok(fit.partnerPersonalityFit < 100);
    assert.equal(await reply(a), null, 'a pending request cannot collect feedback');
    await call(b, "public.marriage_act($1,'accept')", [request]);
    assert.equal(await reply(a), null, 'accepting the request does not open communication yet');
    await signCommunicationAgreement(call, a, b, request);
    const age = days => db.query("update marriage.conversation_pilot set connected_at=now()-$2::integer * interval '1 day' where request_id=$1",[request,days]);
    // The fixture advances through 15 days by backdating the connection.
    await db.query("update marriage.conversation_pilot set enrolled_at=now()-interval '16 days' where request_id=$1",[request]);
    assert.equal(await reply(a),null,'no prompt when chat first opens');
    await age(1);
    assert.equal(await reply(a),null,'no prompt before 48 hours');
    assert.deepEqual(await notices(a), []);
    await age(2);
    const state = (answer, flags = {}) => ({
      answer, mutualContinue:false, initialOpen:true, followupOpen:false, followupTalked:null, ...flags,
    });
    assert.deepEqual(await reply(a), state(null));
    const [firstNotice] = await notices(a);
    assert.deepEqual(firstNotice, {requestId:request, stage:'day2', at:firstNotice.at});
    assert.ok(Date.parse(firstNotice.at));
    assert.deepEqual(await notices(outsider), []);
    assert.equal(await reply(outsider), null);
    assert.equal(await reply(outsider, 'save', {talked:false}), null);
    await assert.rejects(reply(a, 'save', {talked:true, enjoyed:true}), /أكمل/);

    const positive = {talked:true, enjoyed:true, continue:true};
    assert.deepEqual(await reply(a, 'save', positive), state(positive));
    assert.deepEqual(await notices(a), []);
    assert.deepEqual(await notices(b), [firstNotice]);
    assert.deepEqual(await reply(b), state(null));
    assert.deepEqual(await reply(b, 'save', {talked:false, enjoyed:true}), state({talked:false}));
    assert.deepEqual(await reply(a), state(positive));
    assert.deepEqual(await reply(b, 'save', {...positive, enjoyed:false}), state({...positive, enjoyed:false}, {mutualContinue:true}));
    assert.deepEqual(await reply(a), state(positive, {mutualContinue:true}));
    assert.equal(await reply(a, 'followup', {followupTalked:true}), null);
    assert.deepEqual(await reply(b, 'withdraw'), state(null));
    assert.deepEqual(await reply(a), state(positive));

    const totals = () => asService(db, async () => (await db.query('select * from public.marriage_conversation_pilot_totals()')).rows);
    assert.deepEqual(await totals(), []);
    await assert.rejects(call(a, 'public.marriage_conversation_pilot_totals()'), /permission denied/);
    await asMember(db, b.id, b.sessionId, () => assert.rejects(db.query('select * from marriage.conversation_pilot_responses'), /permission denied/));
    const close = () => age(8);
    await close();
    assert.deepEqual((await notices(b)).map(n => n.stage), ['week']);
    assert.equal(await reply(b, 'save', positive), null);
    const weekAnswer={contact:'repeated',enjoyed:'yes',continue:'unsure'};
    await assert.rejects(reply(b,'week',{...weekAnswer,familyContact:'yes'}),/إجابة/);
    await assert.rejects(reply(b,'week',{contact:'none',marriagePotential:'no'}),/إجابة/);
    assert.deepEqual((await reply(b,'week',weekAnswer)).review,weekAnswer,'missing first reply does not gate second window');
    const noContact={instrument:'week-v2',contact:'none'};
    const generalWeek={instrument:'week-v2',contact:'repeated',marriagePotential:'too_early',personalFit:'well',practicalFit:'not_discussed'};
    assert.deepEqual((await reply(b,'week',noContact)).review,noContact);
    assert.deepEqual(await notices(b), []);
    await assert.rejects(reply(b,'week',{...noContact,mainFactor:'values'}),/إجابة/);
    await assert.rejects(reply(b,'week',{...generalWeek,practicalFit:undefined}),/إجابة/);
    await assert.rejects(reply(b,'week',{...generalWeek,mainFactor:'partner_warmth'}),/إجابة/);
    assert.deepEqual((await reply(b,'week',generalWeek)).review,generalWeek);
    assert.equal((await reply(a)).review,null);
    await reply(b,'week',null);
    assert.equal((await totals())[0].unknown, 1);
    await age(3);
    await reply(b, 'save', positive);
    await close();
    const [result] = await totals();
    assert.equal(result.arm, 'candidate');
    assert.equal(result.version, 'marriage-v4');
    assert.equal(result.personality_band, 10);
    assert.equal(result.introductions, 1);
    assert.equal(result.confirmed_conversation, 1);
    assert.equal(result.both_continue, 1);
    assert.equal(result.both_enjoyed_and_continue, 1);
    assert.equal(result.known_failure, 0);
    assert.equal(result.unknown, 0);
    assert.equal(result.followup_eligible, 0, 'follow-up window remains open');

    const followupOpen = {mutualContinue:true, initialOpen:false, followupOpen:true,stage:'week',review:null};
    assert.deepEqual(await reply(a), state(positive, followupOpen));
    assert.equal(await reply(a, 'withdraw'), null, 'first outcome is frozen during follow-up');
    assert.equal(await reply(outsider, 'followup', {followupTalked:true}), null);
    assert.deepEqual(await reply(a, 'followup', {followupTalked:true}), state(positive, {...followupOpen, followupTalked:true}));
    assert.deepEqual(await reply(b), state(positive, followupOpen));
    await reply(b, 'followup', {followupTalked:true});
    assert.deepEqual(await reply(b, 'followup'), state(positive, followupOpen), 'members can clear their own follow-up');
    const closeFollowup = () => age(15);
    await closeFollowup();
    assert.deepEqual(await notices(a), []);
    assert.equal(await reply(a, 'followup', {followupTalked:true}), null);
    let [followup] = await totals();
    assert.equal(followup.followup_eligible, 1);
    assert.equal(followup.confirmed_followup, 0);
    assert.equal(followup.followup_unknown, 1);
    await close();
    await reply(b, 'followup', {followupTalked:true});
    await closeFollowup();
    [followup] = await totals();
    assert.equal(followup.followup_eligible, 1);
    assert.equal(followup.confirmed_followup, 1);
    assert.equal(followup.followup_unknown, 0);
    await close();
    await reply(a,'week',{...generalWeek,marriagePotential:'yes',mainFactor:'respect'});
    await reply(b,'week',generalWeek);
    await closeFollowup();
    await call(a,"public.marriage_act($1,'cancel')",[request]);
    assert.equal((await reply(a)).stage,'exit');
    assert.equal(await reply(a,'week',weekAnswer),null,'closure suppresses the week check-in');
    const exit={contact:'once',enjoyed:'no',continue:'no',reason:'practical',topic:'housing_arrangement'};
    assert.deepEqual((await reply(a,'exit',exit)).review,exit);
    const trainingSql=readFileSync(new URL('../../docs/connection-feedback-training.sql',import.meta.url),'utf8');
    const training=async()=> (await db.query(trainingSql)).rows;
    const rows=await training();
    const cohortSql=readFileSync(new URL('../../docs/marriage-study-cohort.sql',import.meta.url),'utf8');
    const studyBaseline=(await db.query(cohortSql)).rows;
    assert.equal(studyBaseline.length,1,'an ordinary closure stays in the longitudinal cohort');
    assert.ok(studyBaseline[0].practical_topics.some(t=>t.id==='children_plan'));
    assert.equal(rows.length,2,'exit window is still open');
    assert.equal(rows.find(row=>row.stage==='day2').both_enjoyed_and_wanted_to_continue,true);
    const week=rows.find(row=>row.stage==='week');
    assert.equal(week.mutual_perceived_marriage_potential,null);
    assert.equal(week.both_enjoyed_and_wanted_to_continue,null);
    assert.equal(week.both_reported_repeat,true);
    assert.equal(week.requester_personal_fit,'well');
    assert.equal(week.recipient_practical_fit,'not_discussed');
    assert.equal(week.requester_main_factor,'respect');
    assert.equal(week.recipient_main_factor,null);
    assert.equal(rows[0].feature_snapshot.requester.personality.partner_social_energy,'C','frozen before profile edits');
    assert.equal((await reply(b)).review,null,'the peer cannot see a private exit answer');
    assert.equal(await reply(outsider,'exit',exit),null);
    await assert.rejects(reply(b,'exit',{contact:'none',enjoyed:'no'}),/إجابة/);
    await reply(a,'exit',null);
    assert.equal((await reply(a)).review,null);
    await reply(a,'exit',exit);
    await reply(a,'exit',{...exit,enjoyed:'yes',continue:'yes',marriagePotential:'no',familyContact:'yes'});
    await reply(b,'exit',{contact:'once',enjoyed:'yes',continue:'yes',marriagePotential:'too_early',familyContact:'no',
      reason:'personality_strength',topic:'partner_warmth'});
    await db.query("update marriage.member_requests set closed_at=now()-interval '8 days' where id=$1",[request]);
    const ended=(await training()).find(row=>row.stage==='exit');
    assert.equal(ended.both_enjoyed_and_wanted_to_continue,true);
    assert.equal(ended.mutual_perceived_marriage_potential,false,'mutual enjoyment can coexist with one person ruling out marriage');
    assert.equal(ended.corroborated_family_contact,null,'conflicting factual reports stay unresolved');
    assert.equal(ended.recipient.marriagePotential,'too_early');
    assert.equal(ended.requester.topic,'housing_arrangement');
    assert.equal(await reply(a),null,'exit expires after one week');
    await db.query('update marriage.member_requests set closed_at=now() where id=$1',[request]);
    await db.query('insert into marriage.blocks(member_id,blocked_id) values($1,$2)',[a.id,b.id]);
    assert.deepEqual(await notices(a), []);
    assert.deepEqual(await notices(b), []);
    assert.equal(await reply(b),null,'blocking suppresses the exit form for either participant');
    assert.deepEqual(await training(),[]);
  } finally {
    await db.close();
  }
});
