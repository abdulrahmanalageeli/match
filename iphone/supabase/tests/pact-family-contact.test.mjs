import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createDatabase,addUser,asMember} from './harness.mjs';

test('signed pact handoff, mutual exclusivity, private history and safety boundaries',async()=>{
 const db=await createDatabase();
 try {
  await db.query("insert into marriage.cities(label) values('الرياض') on conflict do nothing");
  async function member(gender){
   const u={id:randomUUID(),sessionId:randomUUID(),email:randomUUID()+'@example.test'};
   await addUser(db,u);
   await db.query("update marriage.members set review_status='approved',manual_access_until=now()+interval '1 day' where id=$1",[u.id]);
   await db.query("insert into marriage.profiles(member_id,display_name,age,gender,city_id,profession,bio) values($1,$3,29,$2,(select id from marriage.cities where label='الرياض'),'مهندس','ملف للاختبار')",[u.id,gender,gender==='woman'?'ريم':'سعد']);
   await db.query("insert into marriage.preferences(member_id,min_age,max_age,family_preference) values($1,25,40,'')",[u.id]);
   return u;
  }
  const call=(u,sql,args=[])=>asMember(db,u.id,u.sessionId,async()=>(await db.query('select '+sql+' v',args)).rows[0].v);
  const man=await member('man'),woman=await member('woman'),other=await member('woman');
  const id=await call(man,'public.marriage_request($1)',[woman.id]);
  await call(woman,"public.marriage_act($1,'accept')",[id]);
  const pact=(u,action='read',payload={})=>call(u,'public.marriage_agreement($1,$2,$3)',[id,action,payload]);
  const share=(u,phone,close=false)=>call(u,'public.marriage_share_family_contact($1,$2,$3,true)',[id,phone,close]);
  const read=u=>call(u,'public.marriage_family_contact($1)',[id]);
  const history=u=>call(u,'public.marriage_request_history_item($1)',[id]);
  const message=u=>call(u,'public.marriage_message($1,$2,$3)',[id,'رسالة للاختبار',randomUUID()]);
  assert.equal(await read(man),null);
  await assert.rejects(share(woman,'0501234567',true));
  const proposed=await pact(woman,'propose',{signed:true,days:7});
  await assert.rejects(share(woman,'0501234567',true));
  await pact(man,'accept',{proposalId:proposed.proposalId,signed:true});
  await assert.rejects(share(woman,'0501234567'));
  await assert.rejects(share(man,'0501234567',true));
  await assert.rejects(share(other,'0501234567',true));
  for(const invalid of ['snap:0501234567','0501234567@','https://0501234567','050123456','+971501234567','٠٥٠-۱۲۳X٤٥٦٧','01234567890','0152345678','+966501234567\nabc']){
   await assert.rejects(share(woman,invalid,true));
  }
  await db.query("update auth.users set phone='966501234567',phone_confirmed_at=now() where id=$1",[woman.id]);
  await assert.rejects(share(woman,'0501234567',true));
  await call(man,"public.marriage_push_register($1,'sandbox',$2)",['b'.repeat(64),randomUUID()]);
  await call(man,'public.marriage_push_enable(true)');
  const updates=()=>call(man,'public.marriage_push_updates(null)');
  const shiftDeadline=interval=>db.query("update marriage.conversation_agreements set data=jsonb_set(data,'{deadline}',to_jsonb(now()+$2::interval)) where request_id=$1",[id,interval]);
  const schedule=()=>db.query('select public.nisfayn_enqueue_deadline_reminders()');
  const deadlineJobs=()=>db.query("select event_key,marriage.push_allowed(j) as allowed from marriage.push_outbox j where request_id=$1 and (event_key like 'deadline:%' or event_key like 'agreement:expired:%')",[id]);
  await shiftDeadline('1 hour');await schedule();
  assert.ok((await updates()).some(u=>u.event==='agreement:due'));
  assert.ok((await deadlineJobs()).rows.some(j=>j.allowed));
  await shiftDeadline('-1 second');await schedule();
  // Failure after the first contact write rolls back both the handoff and closure.
  await db.exec("create function public.reject_fixture_close() returns trigger language plpgsql as $$begin raise exception 'fixture close failure';end$$; create trigger reject_close before update of status on marriage.member_requests for each row when(new.status='cancelled') execute function public.reject_fixture_close()");
  await assert.rejects(share(woman,'0111234567',true),/fixture close failure/);
  assert.equal(await read(man),null);
  await db.exec('drop trigger reject_close on marriage.member_requests');
  await share(woman,'٠٠٩٦٦ ۵۵-۱۲۳ ٤٥٦٧');
  await share(woman,'0551234567');
  const notices=(await updates()).filter(u=>u.event==='agreement:family_contact');
  assert.equal(notices.length,1);assert.equal(notices[0].target,id);
  assert.ok(!JSON.stringify(notices).includes('551234567'));
  assert.equal(await read(man),'+966551234567');
  assert.equal(await read(woman),'+966551234567');
  assert.equal(await read(other),null);
  assert.equal((await pact(man)).hasFamilyContact,true);
  assert.ok(!JSON.stringify(await pact(man)).includes('+966'));
  const choice=(u,action,proposal=null)=>call(u,"public.marriage_journey_choice($1,'exclusive',$2,$3,null)",[id,action,proposal]);
  const p=await choice(man,'propose');
  assert.ok((await updates()).some(u=>u.event==='agreement:expired'));
  assert.ok((await deadlineJobs()).rows.some(j=>j.event_key.startsWith('agreement:expired:')&&j.allowed));
  await assert.rejects(message(man));
  await choice(woman,'accept',p.exclusiveId);
  assert.equal((await pact(man)).exclusive,true);
  assert.ok(!(await updates()).some(u=>u.event==='agreement:expired'||u.event==='agreement:due'));
  assert.ok((await deadlineJobs()).rows.every(j=>!j.allowed));
  await db.query("delete from marriage.push_outbox where request_id=$1 and (event_key like 'deadline:%' or event_key like 'agreement:expired:%')",[id]);
  await db.query("delete from marriage.notification_updates where request_id=$1 and (event_key like 'agreement:due:%' or event_key like 'agreement:expired:%')",[id]);
  await schedule();await shiftDeadline('1 hour');await schedule();
  assert.equal((await deadlineJobs()).rows.length,0);
  assert.equal((await db.query("select count(*)::int n from marriage.notification_updates where request_id=$1 and (event_key like 'agreement:due:%' or event_key like 'agreement:expired:%')",[id])).rows[0].n,0);
  await shiftDeadline('-1 second');
  await message(man);
  await choice(woman,'clear',p.exclusiveId);
  assert.equal((await pact(man)).exclusive,false);
  await assert.rejects(message(man));
  await assert.rejects(share(woman,'0111234567'),/سبق تأكيد/);
  await assert.rejects(share(woman,'0111234567',true),/سبق تأكيد/);
  assert.equal(await read(man),'+966551234567');
  assert.equal(await history(man),null);
  await share(woman,'+966 55 123 4567',true);
  await share(woman,'0551234567',true);
  await assert.rejects(share(woman,'0119999999',true));
  assert.equal(await read(man),'+966551234567');
  const row=await history(man);
  assert.equal(row.hasFamilyContact,true);
  assert.equal(row.canRequestAgain,true);
  assert.ok(!JSON.stringify(row).includes('+966'));
  assert.equal((await call(man,'public.marriage_request_history_page(null)')).find(r=>r.id===id).hasFamilyContact,true);
  const closedUpdates=await updates();
  assert.ok(!closedUpdates.some(u=>u.event==='agreement:family_contact'));
  const notice=closedUpdates.find(u=>u.event==='introduction:closed' && u.target===id);
  assert.equal(notice.hasFamilyContact,true);
  assert.ok(!JSON.stringify(notice).includes('+966'));
  assert.equal(await history(other),null);
  await assert.rejects(call(man,'phone from marriage.pact_family_contacts'));
  await db.query("update marriage.member_requests set status='closed' where id=$1",[id]);
  assert.equal(await read(man),null);
  await db.query("update marriage.member_requests set status='cancelled' where id=$1",[id]);
  await db.query("insert into marriage.reports(member_id,reported_id,reason) values($1,$2,'سبب الاختبار')",[woman.id,man.id]);
  assert.equal(await read(man),null);
  assert.equal((await history(man)).hasFamilyContact,false);
  await db.query('delete from marriage.reports where member_id=$1',[woman.id]);
  await db.query('insert into marriage.blocks(member_id,blocked_id) values($1,$2)',[man.id,woman.id]);
  assert.equal(await read(woman),null);
  assert.equal((await history(man)).hasFamilyContact,false);
 } finally { await db.close(); }
});
