import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createDatabase,addUser,asMember,asService} from './harness.mjs';

test('registration-only phase, early access and single-purpose launch delivery', async t=>{
 const db=await createDatabase(); t.after(()=>db.close());
 const create=async()=>{const account={id:randomUUID(),sessionId:randomUUID(),email:randomUUID()+'@example.invalid'};await addUser(db,account);return account;};
 const owner=await create(), waiting=await create(), early=await create(), draft=await create();
 const query=async(sql,args=[]) => (await db.query('select '+sql+' as result',args)).rows[0].result;
 const member=(u,sql,args=[])=>asMember(db,u.id,u.sessionId,()=>query(sql,args));
 const phase=(action='read',revision=null,id=null)=>query('public.wudayn_registration_phase($1,$2,$3)',[action,revision,id]);
 const operate=async(...args)=>{
  const claims={sub:owner.id,session_id:owner.sessionId,role:'authenticated',aal:'aal2'};
  await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(claims)]);
  await db.exec('set role authenticated');
  try{return await phase(...args);} finally{await db.exec('reset role');await db.query("select set_config('request.jwt.claims','',false)");}
 };
 await db.query("insert into marriage.staff_accounts(user_id,display_name,role) values($1,'owner','owner')",[owner.id]);
 await db.query("update marriage.members set review_status='approved' where id in ($1,$2)",[waiting.id,early.id]);
 await assert.rejects(asMember(db,early.id,early.sessionId,()=>phase('lock',0)));
 await assert.rejects(asMember(db,owner.id,owner.sessionId,()=>phase('lock',0)));
 const defaultState=await operate();assert.equal(defaultState.locked,false);
 const closed=await operate('lock',defaultState.revision);assert.equal(closed.locked,true);
 const publicNotice=async()=>{await db.exec('set role anon');try{return (await query("public.wudayn_publications('web',1)")).find(n=>n.key==='registration.phase');}finally{await db.exec('reset role');}};
 assert.equal((await publicNotice()).screen,'welcome');
 const self='public.marriage_state()';
 assert.equal((await member(draft,self)).user.applicationStatus,'draft');
 const receipt={version:'2026-11-07-privacy',registrationVersion:'wudayn-entry-2026-11-23-v3',adult:true,terms:true,privacy:true,assessment:true,sensitiveProfile:true,sensitivePublication:false,photo:false,transcript:false,safetyTextReview:false};
 assert.equal((await member(draft,'public.wudayn_registration_agreements($1,$2)',['accept',receipt])).transcript,false);
 assert.ok(await member(draft,'public.marriage_catalog()'));
 assert.equal((await member(waiting,self)).prelaunch.locked,true);
 const community='public.marriage_inbox()';
 await assert.rejects(member(waiting,community),{code:'42501'});
 await assert.rejects(member(waiting,"public.marriage_discover(null,null,null,null)"),{code:'42501'});
 const permitted=await operate('exclude',closed.revision,early.id);
 assert.equal(permitted.exceptions[0].id,early.id);
 assert.equal((await member(early,self)).prelaunch.locked,false);
 assert.equal(await member(early,"public.wudayn_registration_agreements('read')"),null,'the original member has a historical signup');
 await member(early,community);
 assert.equal((await member(early,"public.wudayn_publications('ios',1)")).some(row=>row.key==='registration.phase'),false);
 assert.equal(await query('marriage.relationship_member_allowed($1)',[waiting.id]),false);
 assert.equal(await query('marriage.relationship_member_allowed($1)',[early.id]),true);
 const install=randomUUID(), otherInstall=randomUUID(),token='a'.repeat(64);
 const register=(u,device,tkn)=>member(u,"public.marriage_push_register($1,'production',$2)",[tkn,device]);
 await register(waiting,install,token);await register(early,otherInstall,'b'.repeat(64));
 await assert.rejects(member(waiting,'public.wudayn_launch_alert(true,$1)',[otherInstall]),{code:'42501'});
 await member(waiting,'public.wudayn_launch_alert(true,$1)',[install]);
 assert.equal((await member(waiting,self)).prelaunch.subscribed,true);
 await member(waiting,'public.wudayn_launch_alert(false)');
 assert.equal((await operate()).subscribers,0);
 await member(waiting,'public.wudayn_launch_alert(true,$1)',[install]);
 assert.equal(await member(waiting,'public.wudayn_news_preference()'),false);
 assert.equal((await member(waiting,'public.marriage_push_settings()')).enabled,false);
 await assert.rejects(operate('launch',closed.revision),{code:'40001'});
 const open=await operate('open',permitted.revision);assert.equal(open.locked,false);assert.equal(open.subscribers,1);
 assert.equal(await query('(select count(*)::int from marriage.push_outbox)'),0);
 assert.equal(await publicNotice(),undefined);
 const again=await operate('lock',open.revision);
 assert.equal(again.exceptions[0].id,early.id);
 const launched=await operate('launch',again.revision);assert.equal(launched.announced,true);
 const unchanged=await operate('launch',launched.revision);assert.equal(unchanged.revision,launched.revision);
 const jobs=await asService(db,()=>query("public.marriage_push_claim('production',20)"));
 assert.equal(jobs.length,1);assert.equal(jobs[0].token,token);
 const details=()=>asService(db,()=>query('public.nisfayn_push_delivery($1,$2,false,$3)',[jobs[0].id,jobs[0].leaseId,token]));
 assert.equal((await details()).launch,true);
 await member(waiting,community);
 const secondWave=await operate('lock',launched.revision);assert.equal(secondWave.subscribers,0);
 assert.equal(await details(),null);
 const noException=await operate('include',secondWave.revision,early.id);assert.equal(noException.exceptions.length,0);
 await assert.rejects(member(early,community),{code:'42501'});
 assert.ok(await query("exists(select from marriage.staff_audit where action='registration_phase_updated')"));
});
