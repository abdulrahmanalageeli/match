async function scalar(db, sql) {
  const result = await db.query(sql)
  return Number(Object.values(result.rows[0])[0])
}

async function seedState(db, testMode = false) {
  await db.exec(`
    insert into event_state(
      match_id, current_event_id, phase, announcement, announcement_type,
      announcement_time, emergency_paused, pause_time, current_round,
      global_timer_active, global_timer_start_time, global_timer_duration,
      global_timer_round, results_visible, groups_locked,
      phase2_score_revealed, phase3_score_revealed, test_mode_active,
      test_mode_snapshot, cohost_locked, cohost_lock_updated_at,
      cohost_lock_updated_by, event3_participant_access_locked
    ) values (
      '${EVENT3_MATCH_ID}', ${EVENT_ID}, 'round3', 'notice', 'warning', now(),
      true, now(), 3, true, now(), 180, 3, true, true, true, true,
      ${testMode}, ${testMode ? `'${JSON.stringify({ started_at: TEST_SESSION })}'::jsonb` : "null"},
      true, now(), 'admin3', true
    );
  `)
}

