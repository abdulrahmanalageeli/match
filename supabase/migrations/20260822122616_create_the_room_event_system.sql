-- Standalone data model for The Room event operations.
-- These tables intentionally have no foreign keys, identifiers, or runtime
-- dependencies on BlindMatch, Event3, or the shared participant directory.

create table public.the_room_events (
  id uuid primary key default gen_random_uuid(),
  event_number bigint not null unique check (event_number > 0),
  name text not null default 'The Room' check (char_length(btrim(name)) between 1 and 120),
  starts_at timestamptz,
  venue text check (venue is null or char_length(venue) <= 240),
  status text not null default 'draft' check (status in ('draft', 'registration', 'ready', 'live', 'completed', 'cancelled')),
  minimum_attendees integer not null default 20 check (minimum_attendees >= 2 and minimum_attendees <= 500),
  table_count integer not null default 5 check (table_count >= 1 and table_count <= 50),
  round_count integer not null default 3 check (round_count >= 1 and round_count <= 20),
  ticket_price numeric(10, 2) not null default 0 check (ticket_price >= 0),
  currency text not null default 'SAR' check (currency ~ '^[A-Z]{3}$'),
  notes text check (notes is null or char_length(notes) <= 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.the_room_attendees (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.the_room_events(id) on delete cascade,
  attendee_number integer not null check (attendee_number > 0),
  full_name text not null check (char_length(btrim(full_name)) between 1 and 160),
  phone_e164 text check (phone_e164 is null or phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  gender text not null default 'unspecified' check (gender in ('male', 'female', 'nonbinary', 'unspecified')),
  attendance_status text not null default 'registered' check (attendance_status in ('registered', 'confirmed', 'waitlist', 'cancelled')),
  included_in_schedule boolean not null default true,
  checked_in boolean not null default false,
  payment_status text not null default 'pending' check (payment_status in ('pending', 'partial', 'paid', 'waived', 'refunded')),
  amount_due numeric(10, 2) not null default 0 check (amount_due >= 0),
  amount_paid numeric(10, 2) not null default 0 check (amount_paid >= 0),
  paid_at timestamptz,
  notes text check (notes is null or char_length(notes) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (event_id, attendee_number),
  unique (id, event_id)
);

create unique index the_room_attendees_event_phone_unique
  on public.the_room_attendees(event_id, phone_e164)
  where phone_e164 is not null;

create index the_room_attendees_event_status_idx
  on public.the_room_attendees(event_id, attendance_status, included_in_schedule);

create index the_room_attendees_event_payment_idx
  on public.the_room_attendees(event_id, payment_status);

create table public.the_room_payment_ledger (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.the_room_events(id) on delete cascade,
  attendee_id uuid not null,
  payment_status text not null check (payment_status in ('pending', 'partial', 'paid', 'waived', 'refunded')),
  amount_paid numeric(10, 2) not null default 0 check (amount_paid >= 0),
  note text check (note is null or char_length(note) <= 1000),
  recorded_by text not null default 'the-room-admin' check (char_length(recorded_by) between 1 and 120),
  recorded_at timestamptz not null default now(),
  foreign key (attendee_id, event_id)
    references public.the_room_attendees(id, event_id) on delete cascade
);

create index the_room_payment_ledger_event_attendee_idx
  on public.the_room_payment_ledger(event_id, attendee_id, recorded_at desc);

create table public.the_room_schedule_runs (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.the_room_events(id) on delete cascade,
  seed text not null check (char_length(seed) between 1 and 200),
  algorithm_version text not null check (char_length(algorithm_version) between 1 and 80),
  participant_count integer not null check (participant_count >= 2),
  table_count integer not null check (table_count >= 1),
  round_count integer not null check (round_count >= 1),
  metrics jsonb not null default '{}'::jsonb check (jsonb_typeof(metrics) = 'object'),
  is_active boolean not null default true,
  generated_at timestamptz not null default now(),
  unique (id, event_id)
);

create unique index the_room_one_active_schedule_per_event
  on public.the_room_schedule_runs(event_id)
  where is_active;

create table public.the_room_seats (
  id bigint generated by default as identity primary key,
  schedule_run_id uuid not null,
  event_id uuid not null,
  round_number integer not null check (round_number >= 1),
  table_number integer not null check (table_number >= 1),
  seat_number integer not null check (seat_number >= 1),
  attendee_id uuid not null,
  created_at timestamptz not null default now(),
  foreign key (schedule_run_id, event_id)
    references public.the_room_schedule_runs(id, event_id) on delete cascade,
  foreign key (attendee_id, event_id)
    references public.the_room_attendees(id, event_id) on delete restrict,
  unique (schedule_run_id, round_number, attendee_id),
  unique (schedule_run_id, round_number, table_number, seat_number)
);

create index the_room_seats_event_round_table_idx
  on public.the_room_seats(event_id, round_number, table_number, seat_number);

comment on table public.the_room_events is
  'Standalone numbered events for The Room; intentionally isolated from BlindMatch and Event3.';
comment on table public.the_room_attendees is
  'Event-scoped The Room guest roster, attendance state, and current payment state.';
comment on table public.the_room_payment_ledger is
  'Append-only history of The Room payment status changes.';
comment on table public.the_room_schedule_runs is
  'Versioned repeat-free table schedule generations for The Room.';
comment on table public.the_room_seats is
  'Round, table, and seat assignments for a The Room schedule generation.';

